"""Builds Telegram/Telegram-iOS/Resources/LumenPyRuntime.js, the plugin runtime bundled into
the app: Skulpt, its standard library, Lumen's Python modules (the exteraGram SDK and stdlib
replacements from Swiftgram/LumenPlugins/Runtime/py) and the host glue (host.js).

Run after changing anything under Swiftgram/LumenPlugins/Runtime and commit the result.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RUNTIME = os.path.join(ROOT, "Swiftgram", "LumenPlugins", "Runtime")
OUTPUT = os.path.join(ROOT, "Telegram", "Telegram-iOS", "Resources", "LumenPyRuntime.js")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def python_modules():
    base = os.path.join(RUNTIME, "py")
    modules = {}
    for folder, _, names in os.walk(base):
        for name in sorted(names):
            if not name.endswith(".py"):
                continue
            full = os.path.join(folder, name)
            relative = os.path.relpath(full, base).replace(os.sep, "/")
            modules["src/lib/" + relative] = read(full).replace("\r\n", "\n")
    return modules


def shadowed_keys(module_path):
    """Skulpt's own files that would be found instead of, or besides, ours."""
    stem = module_path[len("src/lib/"):-len(".py")]
    if stem.endswith("/__init__"):
        stem = stem[:-len("/__init__")]
    return ["src/lib/" + stem + suffix for suffix in (".py", ".js", "/__init__.py", "/__init__.js")]


def build():
    modules = python_modules()
    parts = [
        "// Generated by ci/plugins/build_runtime.py. Do not edit.\n",
        "var window = this; var self = this;\n",
        read(os.path.join(RUNTIME, "vendor", "skulpt.min.js")),
        "\n;\n",
        read(os.path.join(RUNTIME, "vendor", "skulpt-stdlib.js")),
        "\n;\n(function () {\n  var files = Sk.builtinFiles.files;\n",
    ]
    for path in sorted(modules):
        for key in shadowed_keys(path):
            parts.append("  delete files[%s];\n" % json.dumps(key))
    for path in sorted(modules):
        parts.append("  files[%s] = %s;\n" % (json.dumps(path), json.dumps(modules[path], ensure_ascii=False)))
    parts.append("})();\n;\n")
    parts.append(read(os.path.join(RUNTIME, "host.js")))
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(parts))
    print("wrote %s (%d bytes, %d python modules)" % (OUTPUT, os.path.getsize(OUTPUT), len(modules)))


if __name__ == "__main__":
    build()
    sys.exit(0)
