#!/usr/bin/env python3
"""Writes Runtime/py/_lumen_tl_flags.py from the TL schema.

The schema table compiled into the app drops `true` flags (they have no storage), but
Android plugins read and set them as booleans (`request.silent = True`). This module maps
each constructor's true flags to their flags field and bit so the runtime can emulate them.

Run after updating submodules/TelegramApi/swift_scheme.tl, then rebuild the runtime.
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCHEME = os.path.join(ROOT, "submodules", "TelegramApi", "swift_scheme.tl")
OUT = os.path.join(ROOT, "Swiftgram", "LumenPlugins", "Runtime", "py", "_lumen_tl_flags.py")

FLAG = re.compile(r"\b([a-z_][a-z0-9_]*):(flags[0-9]*)\.([0-9]+)\?true\b")


def main():
    entries = {}
    with open(SCHEME, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line or line.startswith("//") or "#" not in line:
                continue
            name = line.split("#", 1)[0].strip()
            flags = FLAG.findall(line)
            if flags:
                entries[name] = flags
    lines = [
        "# Generated by ci/plugins/gen_tl_flags.py from swift_scheme.tl. Do not edit.",
        "# constructor -> 'name:flagsField:bit,...' for its `true` flags.",
        "_RAW = {",
    ]
    for name in sorted(entries):
        packed = ",".join("%s:%s:%s" % flag for flag in entries[name])
        lines.append("    %r: %r," % (name, packed))
    lines += [
        "}",
        "",
        "_cache = {}",
        "",
        "",
        "def true_flags(constructor):",
        "    found = _cache.get(constructor)",
        "    if found is None:",
        "        found = {}",
        "        for item in (_RAW.get(constructor) or '').split(','):",
        "            if item:",
        "                parts = item.split(':')",
        "                found[parts[0]] = (parts[1], int(parts[2]))",
        "        _cache[constructor] = found",
        "    return found",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print("%d constructors, %d flags -> %s" % (len(entries), sum(len(v) for v in entries.values()), OUT))


if __name__ == "__main__":
    main()
